// Table-specific column type overrides
// true = TEXT[] (PostgreSQL array), false = JSONB
const TEXT_ARRAY_COLUMNS = {
  schedules: ['selected_days'],
};

function escapeVal(val, tableName, colName) {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'number') return String(val);
  if (typeof val === 'boolean') return val ? 'TRUE' : 'FALSE';

  if (Array.isArray(val)) {
    // Check if it should be JSONB or TEXT[]
    const isTextArray = TEXT_ARRAY_COLUMNS[tableName]?.includes(colName);
    if (isTextArray) {
      // PostgreSQL array literal: {val1,val2}
      const elements = val.map(v => {
        if (v === null || v === undefined) return 'NULL';
        const s = String(v).replace(/"/g, '\\"');
        return `"${s}"`;
      });
      return `'{${elements.join(',')}}'::text[]`;
    } else {
      // JSONB - use JSON.stringify
      return `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb`;
    }
  }

  if (typeof val === 'object') {
    return `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb`;
  }

  const s = String(val).replace(/'/g, "''");
  return `'${s}'`;
}

async function extractTable(tableName) {
  console.log(`Fetching ${tableName}...`);
  const { data, error } = await source.from(tableName).select('*');
  if (error) {
    console.error(`  Error fetching ${tableName}:`, error.message);
    return [];
  }
  console.log(`  Found ${data.length} rows`);
  return data;
}

function generateInsert(tableName, rows) {
  if (!rows || rows.length === 0) {
    return `-- No data for ${SCHEMA}.${tableName}\n`;
  }
  const cols = Object.keys(rows[0]);
  const lines = rows.map(row => {
    const vals = cols.map(col => escapeVal(row[col], tableName, col));
    return `  (${vals.join(', ')})`;
  });
  let conflict = '';
  if (tableName === 'settings') {
    conflict = ' ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = EXCLUDED.updated_at, updated_by = EXCLUDED.updated_by';
  }
  return `INSERT INTO ${SCHEMA}.${tableName} (${cols.join(', ')}) VALUES\n${lines.join(',\n')}${conflict};\n`;
}

